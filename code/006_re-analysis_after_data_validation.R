# this is the main analysis presented in the manuscript. It uses our own 
# calculating of the effect sizes, as well as:

#### CORRECTIONS OF DATA AND ADDITIONAL DATA FOUND TO BE MISSING DURING OUR
# SUBSET OF REEXTRACTIONS (15% of the studies, see script 004)

# and is in script 05: VARIANCE-COVARIANCE MATRIX for
# modelling the sampling variances. Creating a var-covar matrix assuming a 0.5 
# correlation between effect sizes from the same study, which is a more robust
# and conservative way of modelling these hierarchical structures.

VCV_vi <- vcalc(vi = vi,
                cluster = Authors,
                obs = EffectID,
                data = metadata,
                rho = 0.5)  # assuming that the effect sizes within the same study are correlated with rho = 0.5

phylo.model.r.VCV <- rma.mv(yi = yi,
                            V = VCV_vi,
                            mods = ~ 1,
                            random = list(~ 1 | animal,
                                          ~ 1 | species_phylo,
                                          ~ 1 | Authors,
                                          ~ 1 | EffectID),
                            method = "REML",
                            R = list(species_phylo = phylo_cor.new),
                            test = "t",
                            data = metadata)


print(phylo.model.r.VCV,digits=3)
predict(phylo.model.r.VCV,digits=3)


