# To test small-study effects on r, we follow the general guidelines of Nakagawa
# et al. 2022, MEE. Instead of calculating effective sample size as: 
# (Nr + Nu)/(Nr * Nu), which we could only do for part of the dataset (e.g. not 
# for the correlations), we will simply use the the inverse of the sample size
# and its sqrt.
metadata$inv_esz <-  1/metadata$Sample.Size
metadata$sqrt_inv_esz  <-  with(metadata, sqrt(inv_esz))

# renaming factor levels for Stat.Test
metadata <- as.data.frame(
  metadata %>%
    mutate(Stat.Test = factor(Stat.Test, 
                              levels = c("r","mean","t","F","X2"))) %>%
    mutate(Stat.Test = recode(Stat.Test, r = "Pearson's r",
                              mean = "mean, SD, N",
                              t = "t value",
                              F = "F value",
                              X2 = "X2 value"))
)

