# Heterogeneity: calculating and understanding heterogeneity in the
# intercept-only model not account for phylogeny

# total sampling error
total_se_phylo.model.r.VCV <- sigma2_v(phylo.model.r.VCV)
round(total_se_phylo.model.r.VCV,3)

# total absolute variance
sigma2_phylo.model.r.VCV <- sum(phylo.model.r.VCV$sigma2)
round(sigma2_phylo.model.r.VCV,3)

# ratio of variance to sampling error
round(sigma2_phylo.model.r.VCV/total_se_phylo.model.r.VCV,1)

# I2 = variance-scaled heterogeneity
I2_phylo.model.r.VCV <- orchaRd::i2_ml(phylo.model.r.VCV)
round(I2_phylo.model.r.VCV,2)

# ratio of variance to sampling error: confirmation
round(I2_phylo.model.r.VCV[[1]]/(100-I2_phylo.model.r.VCV[[1]]),1)

